// ═══ رقم العيادة بجانب اسم الدكتور ═══
// الاستقبال تفتح دور الدكتور لتدلّ المرضى، ولا شيء كان يقول لها في أيّ عيادة هو.
// المصدر doctors.room — نفسه على شاشة الصالة وبطاقة الدور المطبوعة، فلا يختلف الرقم
// بين ما تقوله الموظّفة وما يراه المريض. بلا غرفة: تنبيهٌ هادئ كي تُعيَّن قبل الدلالة.
// size="lg" في رأس صفحة الدور، والصغير في قوائم الدكاترة.
export default function RoomBadge({ room, size }) {
  const r = String(room ?? '').trim()
  const cls = `room-badge${size === 'lg' ? ' lg' : ''}${r ? '' : ' none'}`
  return r
    ? <span className={cls}>العيادة {r}</span>
    : <span className={cls} title="عيّن له غرفة من بروفايل الدكتور قبل أن تدلّ المرضى">بلا عيادة</span>
}
